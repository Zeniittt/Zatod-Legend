local data = {
  pagekey = {
    "day",
    "pass",
    "role",
    "ach"
  },
  playerLvKey = {day = "DailyLogin", pass = "DailyPass"},
  dataObj = {},
  reds = {},
  isInit = false
}

function data:init()
  for i, v in ipairs(self.pagekey or {}) do
    package.loaded["ui_new.modules.task.taskData.datas." .. v .. "Data"] = nil
    self.dataObj[v] = require("ui_new.modules.task.taskData.datas." .. v .. "Data")
  end
  return self
end

function data:getPageDataObj(key)
  return self.dataObj[key]
end

function data:taskReply(key, info)
  local refreshType = self.dataObj[key]:refreshData(info)
  self:updateRed(key)
  FireEvent("taskPagesReds", key)
  ListenTimer(Timer:Once(0.2), function()
    FireEvent("MainRedTagChange", ed.ui.configs.mainButton.ButtonType.TASK)
  end)
  return refreshType
end

function data:getRed(key)
  return self.dataObj[key]:getred()
end

function data:getReds()
  for i, v in ipairs(self.pagekey or {}) do
    if not self.playerLvKey[v] or not ed.playerlimit.getAreaUnlockPrompt(self.playerLvKey[v]) then
      local num = self:getRed(v)
      if 0 < num then
        return 1
      end
    end
  end
  return 0
end

function data:updateRed(key)
  local num = self.dataObj[key]:getred()
  if num ~= (self.reds[key] or 0) then
    self.reds[key] = num
  end
end

function data:updateReds()
  for i, v in ipairs(self.pagekey or {}) do
    self:updateRed(v)
  end
end

function data:achievementRed(data)
  self.dataObj.ach:setRed(data)
  FireEvent("taskPagesReds", "ach")
  ListenTimer(Timer:Once(0.2), function()
    FireEvent("MainRedTagChange", ed.ui.configs.mainButton.ButtonType.TASK)
  end)
end

function data:setDailyPassRed(data)
  self.dataObj.pass:setRed(data)
  FireEvent("taskPagesReds", "pass")
  ListenTimer(Timer:Once(0.2), function()
    FireEvent("MainRedTagChange", ed.ui.configs.mainButton.ButtonType.TASK)
  end)
end

function data:addListenEvent()
  return self
end

